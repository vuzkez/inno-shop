using System;
using System.Collections.Generic;
using System.Text;

namespace Inno_Shop.Users.Application.Interfaces
{
    public interface IEmailService
    {
        /// <summary>
        /// Sends an email with a link to confirm the user's email address.
        /// Used after registration, after an email change, and when the user requests the email again.
        /// </summary>
        /// <param name="email">Recipient address.</param>
        /// <param name="userId">User id. It is included in the link so we know whose email is being confirmed.</param>
        /// <param name="token">One-time confirmation token generated by Identity (inserted into the link).</param>
        Task SendEmailConfirmationAsync(string email, string userId, string token);

        /// <summary>
        /// Sends an email with a link to reset the password (account recovery).
        /// </summary>
        /// <param name="email">Recipient address. It is also included in the link.</param>
        /// <param name="token">One-time password reset token generated by Identity.</param>
        Task SendPasswordResetAsync(string email, string token);
    }
}
